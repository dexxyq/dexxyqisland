function tr(key, ...values) {
  const text = document.documentElement.lang === 'en' ? english[key] ?? key : key;
  return values.length ? text.replace(/\{(\d+)\}/g, (_, index) => values[index]) : text;
}

const staticTranslations = [];
const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
while (walker.nextNode()) {
  const node = walker.currentNode;
  if (Object.hasOwn(english, node.data.trim())) staticTranslations.push([node, null, node.data]);
}
for (const element of document.querySelectorAll('[title], [aria-label], [placeholder], [alt]')) {
  for (const attribute of ['aria-label', 'placeholder', 'alt']) {
    const value = element.getAttribute(attribute);
    if (Object.hasOwn(english, value)) staticTranslations.push([element, attribute, value]);
  }
}

function setIslandLanguage(value) {
  const language = value === 'en' ? 'en' : 'ru';
  const previous = document.documentElement.lang;
  document.documentElement.lang = language;
  for (const [node, attribute, original] of staticTranslations) {
    const existing = attribute ? node.getAttribute(attribute) : node.data;
    const englishValue = original.replace(original.trim(), english[original.trim()]);
    if (existing !== original && existing !== englishValue) continue;
    const translated = original.replace(original.trim(), tr(original.trim()));
    if (attribute) node.setAttribute(attribute, translated);
    else node.data = translated;
  }
  try { localStorage.setItem('dexxyq.language', language); } catch {}
  if (previous !== language) window.dispatchEvent(new Event('island-language-change'));
}

